public class Arrays {
    public static void main(String[] args) {
        public class Arrays {
            public static void main(String[] args) {
// in java arrays are used to store multiples data of the same type it is used to store large amount of collection of same type data
                //there are two types of array in java
                //one dimensional
                //two dimensional


                //************************ 1-D array**********************
                int[] numbers = new int[10]; // initialization of array
                //storing data into arrays
                for (int i = 0; i < numbers.length; i++) {
                    numbers[i] = i;
                }
                System.out.println("Data is store ");

                //fetching data from the arraysgit
                for (int i = 0; i < numbers.length; i++) {
                    System.out.println(numbers[i]);

                }
                System.out.println("Data is displayed ");

            }
        }


    }
}
